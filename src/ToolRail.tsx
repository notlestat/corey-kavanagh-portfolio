export function ToolRail() {
  const [active, setActive] = useState<string | null>(null);
  const [instant, setInstant] = useState(false);
  const rail = useRef<HTMLElement>(null);
  const timer = useRef<ReturnType<typeof setTimeout> | null>(null);
  const pinned = useRef<string | null>(null);
  const lastHover = useRef(0);
  const cancelHover = () => {
    if (timer.current !== null) clearTimeout(timer.current);
    timer.current = null;
  };
  const dismiss = () => {
    cancelHover();
    pinned.current = null;
    setActive(null);
  };

  useEffect(() => {
    const outside = (event: Event) => {
      if (event.target instanceof Node && !rail.current?.contains(event.target)) dismiss();
    };
    const escape = (event: KeyboardEvent) => {
      if (event.key === "Escape") dismiss();
    };
    document.addEventListener("pointerdown", outside);
    document.addEventListener("click", outside);
    document.addEventListener("keydown", escape);
    return () => {
      cancelHover();
      document.removeEventListener("pointerdown", outside);
      document.removeEventListener("click", outside);
      document.removeEventListener("keydown", escape);
    };
  }, []);

  return <aside ref={rail} className="home-tools" aria-label="Tools and skills I work with">
    <h2 className="home-tools-heading">Tools &amp; skills</h2>
    <div className="home-tool-marks">
      {tools.map(tool => <button key={tool.id} type="button" className="home-tool-mark"
        aria-label={tool.name} aria-expanded={active === tool.id}
        aria-controls={`home-tool-label-${tool.id}`}
        data-open={active === tool.id} data-instant={instant}
        onPointerEnter={event => {
          if (event.pointerType !== "mouse" || !matchMedia("(hover: hover) and (pointer: fine)").matches || pinned.current) return;
          cancelHover();
          const skipDelay = Date.now() - lastHover.current < 800;
          setInstant(skipDelay);
          const reveal = () => { setActive(tool.id); lastHover.current = Date.now(); };
          if (skipDelay) reveal(); else timer.current = setTimeout(reveal, 180);
        }}
        onPointerLeave={() => {
          cancelHover();
          if (!pinned.current) setActive(null);
        }}
        onFocus={event => {
          if (event.currentTarget.matches(":focus-visible")) {
            cancelHover(); setInstant(true); setActive(tool.id);
          }
        }}
        onBlur={() => { cancelHover(); pinned.current = null; setActive(null); }}
        onClick={() => {
          cancelHover(); setInstant(true);
          pinned.current = pinned.current === tool.id ? null : tool.id;
          setActive(pinned.current);
        }}>
        <svg viewBox={tool.icon === "paper" ? "0 0 21 21" : "0 0 24 24"} fill="currentColor" aria-hidden="true">
            {iconPaths[tool.icon].map((path, index) => <path key={index} d={path} />)}
        </svg>
        <span id={`home-tool-label-${tool.id}`} className="home-tool-name" aria-hidden={active !== tool.id}>{tool.name}</span>
      </button>)}
    </div>
  </aside>;
}
